/*
PROCEDURE_MS_autogen_from_DbD_v1.sql - Auto-generación de Marketing Sources desde Snapshot_day_by_day

Descripción:
  Procedimiento MS_autogen_from_DbD.

Observaciones:

Cada Key debe estar seguida de = y el valor deseado SIN comillas (ni simples ' ni dobles ")
Cada par Key=Value de estar seguido por una COMA
El conjunto de pares [Key=Value] debe ir entre '' (comillas simples) porque forman UN UNICO PARAMETRO string de entrada para el PROCEDURE.

Keys:
InputCommLine = [valor]. Parámetro de entrada.

Month           =[YYYY-MM]. OBLIGATORIO. Mes para seleccionar datos de Snapshot_day_by_day (campo DATE)
Debug           =[No | Yes | KeyValues]. OPCIONAL. Default=No
                  [No] NO EJECUTA QUERY y devuelve el código del Query.
                  [KeyValues] EJECUTA QUERY y devuelve KeyValues del Query.

Parámetros ('[Key=Value[,...]]')

Este procedimiento crea en `campaign_marketing_source` 
todas las `campaign_marketing_source` que debe extraer de Snapshot_day_by_day y que no estén en `campaign_marketing_source`.

Una MS está ya en `campaign_marketing_source` si se cumple lo siguiente:
`Tracker_ID`, `Tracker_Name` y `Username_id` de campaign_marketing_source son iguales a 
`Tracker_ID`, `Tracker_Name` y `Username` de Snapshot_day_by_day

Ejemplos:

call MS_autogen_from_DbD('month=CM,debug=no');
call MS_autogen_from_DbD('month=LM,debug=no');

15.11.2025 v1     Creación inicial

*/

DROP PROCEDURE IF EXISTS MS_autogen_from_DbD;

DELIMITER $$
CREATE DEFINER=`b3w1nn3r`@`%` PROCEDURE `MS_autogen_from_DbD`(IN
   InputCommLine    VARCHAR(250)
   )
    COMMENT 'MS_autogen_from_DbD - Auto-generación de Marketing Sources desde Snapshot_day_by_day'
    
proc_label:BEGIN
-- --------------------------------------------------------------------------------------------
-- Defaults
SET @Version         ='v1 15.11.2025';
SET @CurrentDay      =curdate();

SET @Month           =left(curdate(),7);
SET @Debug           ='NO';

SET @InputCommLine=Concat(InputCommLine ,',');      -- Coma de cierre
SET @InputCommLine=replace(@InputCommLine,'"','');  -- Elimina comillas

-- IF @Debug!="NO" THEN SELECT @InputCommLine; END IF;

-- Parseo de parámetros
WHILE @InputCommLine>' ' DO
   SET @e=INSTR(@InputCommLine,'=');    				   -- Posición del =
   SET @c=INSTR(@InputCommLine,','); 					   -- Posición de la coma
   SET @k=SUBSTRING(@InputCommLine,1,@e-1); 			   -- Key
   SET @v=SUBSTRING(@InputCommLine,@e+1,@c-(@e+1)); 	-- Value
   SET @InputCommLine=SUBSTRING(@InputCommLine,@c+1);
   SET @k=TRIM(@k);
   SET @v=TRIM(@v);   

   IF lower(@k)='month'          THEN SET @Month         =      @v;  END IF;
   IF lower(@k)='debug'          THEN SET @Debug         =UPPER(@v); END IF;

END WHILE;

-- IF @Debug!="NO" THEN SELECT @Month,@Debug,InputCommLine; END IF;

IF @Month='CM' THEN SET @Month=LEFT(DATE_SUB(CURDATE(), INTERVAL 0 MONTH),7); END IF;
IF @Month='LM' THEN SET @Month=LEFT(DATE_SUB(CURDATE(), INTERVAL 1 MONTH),7); END IF;

-- Obtiene @AutogenDefaultUser desde tabla util_settings
SET @AutogenDefaultUser=(SELECT `Value_01`    FROM `util_settings` WHERE Setting='AutogenDefaultUser');
SET @AutogenDefaultChannel=(SELECT `Value_01` FROM `util_settings` WHERE Setting='AutogenDefaultChannel');
SET @AutogenDefaultDeal=(SELECT `Value_01`    FROM `util_settings` WHERE Setting='AutogenDefaultDeal');

IF @Debug!="NO" THEN SELECT @AutogenDefaultUser,@AutogenDefaultChannel,@AutogenDefaultDeal; END IF;

-- Query principal: Insertar registros faltantes
SET @SQL = CONCAT('
INSERT INTO campaign_marketing_source
   (`Tracker_ID`, `Tracker_Name`, `Code_To_Affiliate`, `Code`, `Affiliate_id`, `Advertiser_id`, `Publisher_id`, `Username_id`
   ,Status_id,Status 
   ,Deal_id,Country_Deal,Deal_Valid_From,Product_Deal
   ,Description,`Owner`,Channel_id,`Operator`)  
SELECT DISTINCT
   D.`Tracker_ID`,
   D.`Tracker_Name`,
   D.`Tracker_Name` AS `Code_To_Affiliate`,
   D.`Tracker_ID` AS `Code`,
   @AutogenDefaultUser AS `Affiliate_id`,
   CU.`Advertiser_id`,
   CU.`Publisher_id`,
   CU.`id` AS `Username_id`,
   "1" AS `Status_id`,
   "Active" AS `Status`,
   @AutogenDefaultDeal AS `Deal_id`,
   "" AS `Country_Deal`,
   "2025-01-01" AS `Deal_Valid_From`,
   "" AS `Product_Deal`,
   concat("Autogenerated ",curdate()) AS `Description`,
   CU.`Owner` AS `Owner`,
   @AutogenDefaultChannel AS `Channel_id`,
   "SysOp" AS `Operator`
   FROM `Snapshot_day_by_day` D
INNER JOIN `campaign_username` CU ON CU.`id` = D.`Username`
LEFT JOIN `campaign_marketing_source` MS ON 
   MS.`Username_id` = CU.`id`
   AND (MS.`Tracker_ID` = D.`Tracker_ID` 
   OR MS.`Tracker_Name` = D.`Tracker_Name`)
WHERE LEFT(D.`Date`, 7) = ''', @Month, '''
   AND MS.`id` IS NULL  -- Solo los que NO existen en campaign_marketing_source
   AND D.`Tracker_ID` IS NOT NULL 
   AND D.`Tracker_ID` != ''''
   AND D.`Tracker_Name` IS NOT NULL 
   AND D.`Tracker_Name` != ''''
   AND D.`Username` IS NOT NULL 
   AND D.`Username` != ''''
   AND CU.`id` IS NOT NULL
   AND CU.`Advertiser_id` IS NOT NULL
   AND CU.`Publisher_id` IS NOT NULL
');

IF @Debug!="NO" THEN SELECT @SQL; END IF;

IF @Debug != "YES" THEN
   PREPARE stmt1 FROM @SQL;
   EXECUTE stmt1;
   DEALLOCATE PREPARE stmt1;
   
   -- Mostrar resumen de registros insertados
   -- SELECT 
   --    COUNT(*) AS `Registros_Insertados`,
   --    @Month AS `Mes_Procesado`
   -- FROM campaign_marketing_source_missing
   -- WHERE LEFT(Creation_Date, 7) = @Month;
END IF;

END$$
DELIMITER ;

